const TOOL_REGISTRY = {
  'docx-to-pdf': { accept: ['.docx', '.doc'], outExt: '.pdf' },
  'pdf-to-image': { accept: ['.pdf'], outExt: '.zip' },
  'unzip-file': { accept: ['.zip'], outExt: '.png' },
  'image-compressor': { accept: ['.png', '.jpg', '.jpeg', '.webp'], outExt: '.jpg' },
  'pdf-to-word': { accept: ['.pdf'], outExt: '.docx' }
};

const ROW_HEIGHT = 160;

function optimizeCanvasLayout(operations, workspaceQueue) {
  const updatedQueue = [...workspaceQueue];
  const updatedOps = [...operations];
  
  const nodeLayers = {};
  
  // Define helper to trace output generators
  const isGeneratedFile = (fileId) => {
    return updatedOps.some(op => {
      const outIds = op.outputIds || (op.outputId ? [op.outputId] : []);
      return outIds.includes(fileId);
    });
  };

  // Layer 0: Original input files (no parent operators)
  updatedQueue.forEach(file => {
    if (!isGeneratedFile(file.id)) {
      nodeLayers[file.id] = 0;
    }
  });

  // Layer assignment logic using the relative layering rule:
  // Downstream operators are pushed 2 layers to the right of parent operators
  let changed = true;
  let iterations = 0;
  while (changed && iterations < 15) {
    changed = false;
    iterations++;

    // Assign layers to operations
    updatedOps.forEach(op => {
      let maxParentLayer = -1;
      let allParentsAssigned = true;

      op.inputIds.forEach(parentId => {
        if (nodeLayers[parentId] !== undefined) {
          const effectiveParentLayer = parentId.startsWith('op-') 
            ? nodeLayers[parentId] + 1 
            : nodeLayers[parentId];
          maxParentLayer = Math.max(maxParentLayer, effectiveParentLayer);
        } else {
          allParentsAssigned = false;
        }
      });

      if (allParentsAssigned && maxParentLayer !== -1) {
        const assignedLayer = maxParentLayer + 1;
        if (nodeLayers[op.id] !== assignedLayer) {
          nodeLayers[op.id] = assignedLayer;
          changed = true;
        }
      }
    });

    // Assign layers to intermediate files generated by operations
    updatedOps.forEach(op => {
      if (nodeLayers[op.id] !== undefined) {
        const fileLayer = nodeLayers[op.id] + 1;
        const outIds = op.outputIds || (op.outputId ? [op.outputId] : []);
        outIds.forEach(fileId => {
          if (nodeLayers[fileId] !== fileLayer) {
            nodeLayers[fileId] = fileLayer;
            changed = true;
          }
        });
      }
    });
  }

  // Position nodes horizontally based on layer (300px column gap)
  const allNodes = [];
  updatedQueue.forEach(file => {
    const layer = nodeLayers[file.id] || 0;
    allNodes.push({ id: file.id, type: 'file', name: file.name, layer, x: 80 + layer * 300, y: file.y || 100 });
  });

  updatedOps.forEach(op => {
    const layer = nodeLayers[op.id] || 1;
    allNodes.push({ id: op.id, type: 'op', name: op.toolId, layer, x: 80 + layer * 300, y: op.y || 100 });
  });

  // Check for horizontal collisions in columns
  const layerBuckets = {};
  allNodes.forEach(node => {
    if (!layerBuckets[node.layer]) layerBuckets[node.layer] = [];
    layerBuckets[node.layer].push(node);
  });

  // Evenly spread nodes vertically in each layer to prevent overlap
  Object.keys(layerBuckets).forEach(layer => {
    const nodesInLayer = layerBuckets[layer];
    nodesInLayer.forEach((node, idx) => {
      node.y = 80 + idx * ROW_HEIGHT;
    });
  });

  return allNodes;
}

// Replicate cascade compiler loop
function simulatePipelineHealAndLayout() {
  console.log("==================================================================");
  console.log("DocForge Cascading Pipeline Simulation & Layout Collision Test");
  console.log("==================================================================");

  // Scenario: Word File (.docx) directly connected to Image Compressor (expects png/jpg)
  const initialQueue = [
    { id: 'file-docx', name: 'report.docx', x: 80, y: 120 }
  ];

  const initialOps = [
    { id: 'op-compressor', toolId: 'image-compressor', inputIds: ['file-docx'], outputIds: ['file-compressed-jpg'], x: 500, y: 120 }
  ];

  console.log("Initial state compiled. Performing connection checks and healing...");

  let currentOps = [...initialOps];
  let currentQueue = [...initialQueue];

  // Simulation of loop running validateCanvasConnections and executeAutoHeal
  // Step 1: Mismatch detected - '.docx' connected to image-compressor. Injects docx-to-pdf.
  console.log("\n[Heal Step 1] Injected 'docx-to-pdf' to convert Word -> PDF");
  const docxToPdfOpId = 'op-docx-to-pdf';
  const intermediatePdfId = 'file-intermediate-pdf';
  
  // Rewire docx -> docx-to-pdf -> intermediate-pdf -> compressor
  currentOps = [
    { id: docxToPdfOpId, toolId: 'docx-to-pdf', inputIds: ['file-docx'], outputIds: [intermediatePdfId] },
    { id: 'op-compressor', toolId: 'image-compressor', inputIds: [intermediatePdfId], outputIds: ['file-compressed-jpg'] }
  ];
  currentQueue.push({ id: intermediatePdfId, name: 'report.pdf' });

  // Step 2: Mismatch detected - '.pdf' connected to image-compressor. Injects pdf-to-image.
  console.log("[Heal Step 2] Injected 'pdf-to-image' to convert PDF -> Image Zip");
  const pdfToImageOpId = 'op-pdf-to-image';
  const intermediateZipId = 'file-intermediate-zip';

  currentOps = [
    { id: docxToPdfOpId, toolId: 'docx-to-pdf', inputIds: ['file-docx'], outputIds: [intermediatePdfId] },
    { id: pdfToImageOpId, toolId: 'pdf-to-image', inputIds: [intermediatePdfId], outputIds: [intermediateZipId] },
    { id: 'op-compressor', toolId: 'image-compressor', inputIds: [intermediateZipId], outputIds: ['file-compressed-jpg'] }
  ];
  currentQueue.push({ id: intermediateZipId, name: 'report_images.zip' });

  // Step 3: Mismatch detected - '.zip' connected to image-compressor. Injects unzip-file.
  console.log("[Heal Step 3] Injected 'unzip-file' to decompress Zip -> PNG");
  const unzipOpId = 'op-unzip-file';
  const intermediatePngId = 'file-intermediate-png';

  currentOps = [
    { id: docxToPdfOpId, toolId: 'docx-to-pdf', inputIds: ['file-docx'], outputIds: [intermediatePdfId] },
    { id: pdfToImageOpId, toolId: 'pdf-to-image', inputIds: [intermediatePdfId], outputIds: [intermediateZipId] },
    { id: unzipOpId, toolId: 'unzip-file', inputIds: [intermediateZipId], outputIds: [intermediatePngId] },
    { id: 'op-compressor', toolId: 'image-compressor', inputIds: [intermediatePngId], outputIds: ['file-compressed-jpg'] }
  ];
  currentQueue.push({ id: intermediatePngId, name: 'report_page1.png' });

  // Run layout optimizer on the final fully healed cascade chain
  const resultLayout = optimizeCanvasLayout(currentOps, currentQueue);

  console.log("\nLayout Results (Nodes Sorted by Horizontal X Coordinate):");
  resultLayout.sort((a, b) => a.x - b.x || a.y - b.y);
  
  resultLayout.forEach(node => {
    console.log(`- [Layer ${node.layer}] ID: ${node.id.padEnd(23)} | Type: ${node.type.padEnd(4)} | Name: ${node.name.padEnd(16)} | X: ${String(node.x).padEnd(4)} | Y: ${node.y}`);
  });

  // Verify that there are no horizontal/vertical coordinate collisions
  const coordinateSet = new Set();
  let overlapFound = false;
  resultLayout.forEach(node => {
    const key = `${node.x},${node.y}`;
    if (coordinateSet.has(key)) {
      overlapFound = true;
      console.log(`[COLLISION ERROR] Overlap detected at ${key}`);
    }
    coordinateSet.add(key);
  });

  if (!overlapFound) {
    console.log("\n[SUCCESS] Verification complete: All 9 nodes are positioned in structured, collision-free columns!");
  } else {
    console.log("\n[FAILURE] Layout coordinate collision detected!");
  }
}

simulatePipelineHealAndLayout();
