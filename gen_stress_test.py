# Assemble the document
parts = [HEADER]
current_size = len(HEADER.encode("utf-8")) + len(FOOTER.encode("utf-8"))
i = 1

while current_size < TARGET_SIZE:
    section = make_section(i)
    sb = section.encode("utf-8")
    if current_size + len(sb) > TARGET_SIZE:
        # Pad with HTML comment data to reach exact target
        remaining = int(TARGET_SIZE - current_size) - 10
        pad_unit = "DocForge boundary-pad block. Section {i}. Checksum-{i}. ".format(i=i)
        padding = "<!-- "
        while len((padding + pad_unit).encode("utf-8")) < remaining:
            padding += pad_unit
        padding = padding[:remaining] + " -->"
        parts.append(padding)
        current_size += len(padding.encode("utf-8"))
        break
    parts.append(section)
    current_size += len(sb)
    i += 1

parts.append(FOOTER)
content = "".join(parts)

output_path = r"c:\Users\Tanvir Alam\Downloads\New folder upscaled\critical_stress_14mb.html"
