/**
 * Strips protocol and www prefixes for clean, legible profile display.
 */
function cleanUrl(url) {
  if (!url || typeof url !== 'string') return '';
  return url.replace(/^https?:\/\/(www\.)?/i, '').trim();
}

/**
 * Extracts a concise username or handle from a GitHub URL or string.
 */
function getGithubHandle(raw) {
  const clean = cleanUrl(raw);
  return clean.replace(/^github\.com\//i, '').replace(/\/$/, '');
}

/**
 * Scans generated template HTML and seamlessly injects any omitted user data fields
 * (GitHub, References, Custom Sections, Certifications) matching the template's
 * typography and color scheme, stamped with canonical data-df-field attributes.
 *
 * @param {string} rawHtml - HTML string generated by any of the 89 templates
 * @param {object} data - Normalized candidate data
 * @param {object} theme - Active theme options (themeColor, themeFont, etc.)
 * @returns {string} Enriched HTML with 100% field coverage
 */
export function ensureTemplateFieldParity(rawHtml, data, theme = {}) {
  if (!rawHtml || typeof rawHtml !== 'string') return rawHtml || '';
  if (!data || typeof data !== 'object') return rawHtml;

  let html = rawHtml;

  // Extract design tokens from active theme
  const isThemeObj = typeof theme === 'object' && theme !== null && !Array.isArray(theme);
  const rawAccent = isThemeObj ? (theme.primaryColor || theme.themeColor || '#2563eb') : (typeof theme === 'string' && theme !== 'default' && theme ? theme : '#2563eb');
  const safeAccent = rawAccent === 'default' || !rawAccent ? '#2563eb' : rawAccent;
  const themeFont = isThemeObj ? (theme.font || theme.themeFont || '') : '';
  const fontStyle = themeFont ? `font-family: '${themeFont}', -apple-system, BlinkMacSystemFont, 'Segoe UI', Roboto, sans-serif;` : '';

  // ── 1. GitHub Profile Parity ──
  const rawGithub = data.github ? String(data.github).trim() : '';
  if (rawGithub) {
    const handle = getGithubHandle(rawGithub);
    const hasGithubTag = html.includes('data-df-field="github"') || html.includes('github.com/' + handle);

    if (!hasGithubTag && handle) {
      const gitLink = 'https://github.com/' + handle;
      const gitNode = '<a data-df-field="github" href="' + gitLink + '" target="_blank" style="color: inherit; text-decoration: none;" title="GitHub Profile">github.com/' + handle + '</a>';

      // Priority 1: Contact bar / row with separators
      if (html.includes('class="contact-bar"') || html.includes('class="main-contact-bar"')) {
        html = html.replace(/(<(?:div|header|p)[^>]*class="(?:[^"]* )?(?:contact-bar|main-contact-bar)[^"]*"[^>]*>[\s\S]*?)(<\/(?:div|header|p)>)/i, (m, p1, p2) => {
          return p1 + ' <span class="separator"> · </span>' + gitNode + p2;
        });
      }
      // Priority 2: Sidebar contact list
      else if (html.includes('sidebar-contact-list') || html.includes('contact-list')) {
        const itemHtml = '<div class="contact-item contact-row"><span class="label">GitHub</span><span class="val">' + gitNode + '</span></div>';
        html = html.replace(/(<(?:div|ul)[^>]*class="(?:[^"]* )?(?:sidebar-contact-list|contact-list)[^"]*"[^>]*>[\s\S]*?)(<\/(?:div|ul)>)/i, (m, p1, p2) => {
          return p1 + itemHtml + p2;
        });
      }
      // Priority 3: Generic contact class
      else if (html.includes('class="contact"')) {
        html = html.replace(/(<div[^>]*class="(?:[^"]* )?contact[^"]*"[^>]*>[\s\S]*?)(<\/div>)/i, (m, p1, p2) => {
          return p1 + '  |  ' + gitNode + p2;
        });
      }
      // Priority 4: Append near email or phone
      else if (html.includes('data-df-field="email"')) {
        html = html.replace(/(<a[^>]*data-df-field="email"[^>]*>[\s\S]*?<\/a>)/i, (m, p1) => {
          return p1 + ' <span class="separator"> · </span>' + gitNode;
        });
      }
      else if (html.includes('data-df-field="phone"')) {
        html = html.replace(/(<span[^>]*data-df-field="phone"[^>]*>[\s\S]*?<\/span>)/i, (m, p1) => {
          return p1 + ' <span class="separator"> · </span>' + gitNode;
        });
      }
      // Priority 5: Fallback near title or name
      else if (html.includes('data-df-field="title"')) {
        html = html.replace(/(<[^>]*data-df-field="title"[^>]*>[\s\S]*?<\/[^>]+>)/i, (m, p1) => {
          return p1 + '<div class="contact-bar-parity" style="margin-top: 4px; font-size: 8.5pt;">' + gitNode + '</div>';
        });
      }
      else if (html.includes('data-df-field="name"')) {
        html = html.replace(/(<[^>]*data-df-field="name"[^>]*>[\s\S]*?<\/[^>]+>)/i, (m, p1) => {
          return p1 + '<div class="contact-bar-parity" style="margin-top: 4px; font-size: 8.5pt;">' + gitNode + '</div>';
        });
      }
    }
  }

  // ── 2. Certifications Parity ──
  const certs = Array.isArray(data.certifications) ? data.certifications.filter(Boolean) : [];
  if (certs.length > 0) {
    const hasCertTag = html.includes('data-df-field="heading:certifications"') || html.includes('data-df-field="cert:0');

    if (!hasCertTag) {
      const certTitle = data.sectionTitles?.certifications || 'Certifications';
      const certMarkup = [
        '<section class="section-block cert-section main-section" style="margin-top: 14px; break-inside: avoid; ' + fontStyle + '">',
        '  <h3 class="section-title section-heading" data-df-field="heading:certifications" style="font-size: 11pt; font-weight: 700; text-transform: uppercase; letter-spacing: 0.5px; margin-bottom: 6px; border-bottom: 2px solid ' + safeAccent + '30; padding-bottom: 3px; color: inherit;">' + certTitle + '</h3>',
        '  <ul class="cert-list" style="padding-left: 18px; margin: 4px 0 0 0; font-size: 9pt; line-height: 1.45;">',
        certs.map((c, idx) => '    <li style="margin-bottom: 3px;"><span data-df-field="cert:' + idx + '">' + (typeof c === 'string' ? c : (c.name || c.title || '')) + '</span></li>').join('\n'),
        '  </ul>',
        '</section>'
      ].join('\n');

      if (html.includes('class="main-col"') || html.includes('class="main-content"')) {
        html = html.replace(/(<(?:div|main)[^>]*class="(?:[^"]* )?(?:main-col|main-content)[^"]*"[^>]*>[\s\S]*?)(<\/(?:div|main)>)/i, (m, p1, p2) => {
          return p1 + certMarkup + p2;
        });
      } else if (html.includes('id="page-1"')) {
        html = html.replace(/(<div[^>]*id="page-1"[^>]*>[\s\S]*?)(<\/div>[\s\n]*(?:<(?:div class="cv-page|script|\/body)|$))/i, (m, p1, p2) => {
          return p1 + certMarkup + p2;
        });
      } else if (html.includes('class="cv-page"') || html.includes('class="resume-card"')) {
        html = html.replace(/(<(?:div|section)[^>]*class="(?:[^"]* )?(?:cv-page|resume-card)[^"]*"[^>]*>[\s\S]*?)(<\/(?:div|section)>)/i, (m, p1, p2) => {
          return p1 + certMarkup + p2;
        });
      } else {
        html = html.replace(/<\/body>/i, certMarkup + '</body>');
      }
    }
  }

  // ── 3. References Parity ──
  const refs = Array.isArray(data.references) ? data.references.filter(Boolean) : [];
  if (refs.length > 0) {
    const hasRefTag = html.includes('data-df-field="heading:references"') || html.includes('data-df-field="ref:0:name"');

    if (!hasRefTag) {
      const refTitle = data.sectionTitles?.references || 'References';
      const refItems = refs.map((r, idx) => {
        const contactLine = (r.phone ? 'Phone: ' + r.phone : '') + (r.phone && r.email ? ' · ' : '') + (r.email ? 'Email: ' + r.email : '');
        return [
          '    <div class="ref-item entry-item" style="font-size: 8.8pt; line-height: 1.35; padding: 8px 12px; background: rgba(0,0,0,0.02); border-left: 3px solid ' + safeAccent + '; border-radius: 2px;">',
          '      <div style="font-weight: 700; color: inherit; margin-bottom: 2px;" data-df-field="ref:' + idx + ':name">' + (r.name || 'Reference Name') + '</div>',
          '      <div style="font-style: italic; opacity: 0.85; font-size: 8.2pt; margin-bottom: 2px;" data-df-field="ref:' + idx + ':relation">' + (r.relation || '') + '</div>',
          '      <div style="font-size: 8pt; opacity: 0.75; font-weight: 500;" data-df-field="ref:' + idx + ':contact">' + contactLine + '</div>',
          '    </div>'
        ].join('\n');
      }).join('\n');

      const refMarkup = [
        '<section class="section-block references-section main-section" style="margin-top: 14px; break-inside: avoid; ' + fontStyle + '">',
        '  <h3 class="section-title section-heading" data-df-field="heading:references" style="font-size: 11pt; font-weight: 700; text-transform: uppercase; letter-spacing: 0.5px; margin-bottom: 6px; border-bottom: 2px solid ' + safeAccent + '30; padding-bottom: 3px; color: inherit;">' + refTitle + '</h3>',
        '  <div class="references-grid" style="display: grid; grid-template-columns: repeat(auto-fit, minmax(220px, 1fr)); gap: 10px; margin-top: 8px;">',
        refItems,
        '  </div>',
        '</section>'
      ].join('\n');

      if (html.includes('class="main-col"') || html.includes('class="main-content"')) {
        html = html.replace(/(<(?:div|main)[^>]*class="(?:[^"]* )?(?:main-col|main-content)[^"]*"[^>]*>[\s\S]*?)(<\/(?:div|main)>)/i, (m, p1, p2) => {
          return p1 + refMarkup + p2;
        });
      } else if (html.includes('id="page-1"')) {
        html = html.replace(/(<div[^>]*id="page-1"[^>]*>[\s\S]*?)(<\/div>[\s\n]*(?:<(?:div class="cv-page|script|\/body)|$))/i, (m, p1, p2) => {
          return p1 + refMarkup + p2;
        });
      } else if (html.includes('class="cv-page"') || html.includes('class="resume-card"')) {
        html = html.replace(/(<(?:div|section)[^>]*class="(?:[^"]* )?(?:cv-page|resume-card)[^"]*"[^>]*>[\s\S]*?)(<\/(?:div|section)>)/i, (m, p1, p2) => {
          return p1 + refMarkup + p2;
        });
      } else {
        html = html.replace(/<\/body>/i, refMarkup + '</body>');
      }
    }
  }

  // ── 4. Custom Sections & Languages Parity ──
  const customSections = Array.isArray(data.customSections) ? data.customSections.filter(cs => cs && Array.isArray(cs.items) && cs.items.length > 0) : [];
  for (const cs of customSections) {
    const hasSection = html.includes('data-df-field="custom:' + cs.id + ':title"') || html.includes('data-df-field="custom:' + cs.id + ':0:title"');
    if (!hasSection) {
      const itemsMarkup = cs.items.map((it, idx) => {
        const titleStr = typeof it === 'string' ? it : (it.title || it.name || '');
        const valStr = typeof it === 'object' && it !== null && it.value ? ': <span data-df-field="custom:' + cs.id + ':' + idx + ':value">' + it.value + '</span>' : '';
        return '    <div class="custom-item" style="font-size: 8.8pt; line-height: 1.35; padding: 4px 8px; background: rgba(0,0,0,0.015); border-radius: 3px;"><strong data-df-field="custom:' + cs.id + ':' + idx + ':title">' + titleStr + '</strong>' + valStr + '</div>';
      }).join('\n');

      const csMarkup = [
        '<section class="section-block custom-section main-section" style="margin-top: 14px; break-inside: avoid; ' + fontStyle + '">',
        '  <h3 class="section-title section-heading" data-df-field="custom:' + cs.id + ':title" style="font-size: 11pt; font-weight: 700; text-transform: uppercase; letter-spacing: 0.5px; margin-bottom: 6px; border-bottom: 2px solid ' + safeAccent + '30; padding-bottom: 3px; color: inherit;">' + (cs.title || 'Additional Information') + '</h3>',
        '  <div style="display: grid; grid-template-columns: repeat(auto-fit, minmax(180px, 1fr)); gap: 8px; margin-top: 6px;">',
        itemsMarkup,
        '  </div>',
        '</section>'
      ].join('\n');

      if (html.includes('class="main-col"') || html.includes('class="main-content"')) {
        html = html.replace(/(<(?:div|main)[^>]*class="(?:[^"]* )?(?:main-col|main-content)[^"]*"[^>]*>[\s\S]*?)(<\/(?:div|main)>)/i, (m, p1, p2) => {
          return p1 + csMarkup + p2;
        });
      } else if (html.includes('id="page-1"')) {
        html = html.replace(/(<div[^>]*id="page-1"[^>]*>[\s\S]*?)(<\/div>[\s\n]*(?:<(?:div class="cv-page|script|\/body)|$))/i, (m, p1, p2) => {
          return p1 + csMarkup + p2;
        });
      } else if (html.includes('class="cv-page"') || html.includes('class="resume-card"')) {
        html = html.replace(/(<(?:div|section)[^>]*class="(?:[^"]* )?(?:cv-page|resume-card)[^"]*"[^>]*>[\s\S]*?)(<\/(?:div|section)>)/i, (m, p1, p2) => {
          return p1 + csMarkup + p2;
        });
      } else {
        html = html.replace(/<\/body>/i, csMarkup + '</body>');
      }
    }
  }

  return html;
}

export default {
  ensureTemplateFieldParity
};
